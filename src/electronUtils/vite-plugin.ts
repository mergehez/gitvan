import fs from 'fs';
import { resolve } from 'path';
import type { PluginOption } from 'vite';

type Options = {
    app: string;
    main: string;
    preload: string;
    devServer: string;
    apiMethods: string;
};

function generateApiMethods(paths: Options) {
    // Extract backend method names from app.ts: methodName: async (ps) => {
    // Exclude getter/IIFE patterns where name: (() => { ... })()
    const appContent = fs.readFileSync(paths.app, 'utf-8');
    const appLines = appContent.split('export const app = {').pop()!.split('\n');
    const backendMethodMatches = [...appContent.matchAll(/^    ([a-zA-Z]+):\s+(async\s+)?\(/gm)];
    const backendMethods = backendMethodMatches
        .filter((m) => {
            const lineIndex = appContent.substring(0, m.index).split('\n').length - 1;
            const line = appLines[lineIndex];
            // Skip IIFE getter patterns like: name: (() => { ... })()
            return !/:\s*\(\(\)/.test(line);
        })
        .map((m) => m[1]);

    // Extract native method names from main.ts: methodName: async (ps) => { in createNativeHandlers
    const handlersContent = fs.readFileSync(paths.main, 'utf-8');
    const nativeMethods = [...handlersContent.matchAll(/^\s+([a-zA-Z]+):\s+async\s+\(/gm)].map((m) => m[1]);

    const allMethods = [...new Set([...backendMethods, ...nativeMethods])].sort();
    const names = allMethods.map((name) => `'${name}'`).join(',\n    ');

    let content = '// This file is auto-generated by src/electronUtils/vite-plugin.ts';
    content += `\nexport const apiMethods = [\n    ${names},\n] as const;\n`;

    fs.writeFileSync(paths.apiMethods, content);
}
// console.log('Exporting backend + native method names to src/shared/apiMethods.ts...', appPath, mainPath);
const electronPlugin = (paths: Options): PluginOption => {
    paths.app = resolve(paths.app);
    paths.main = resolve(paths.main);
    paths.preload = resolve(paths.preload);
    paths.devServer = resolve(paths.devServer);
    paths.apiMethods = resolve(paths.apiMethods);
    return {
        name: 'export-api-methods',
        buildStart() {
            // console.log('Exporting backend + native method names to src/shared/apiMethods.ts...', appPath, mainPath);
            generateApiMethods(paths);
        },
        configureServer(server) {
            server.watcher.add([paths.app, paths.main]);
            server.watcher.on('change', (file) => {
                console.log(file);
                if (file === paths.app || file === paths.main) {
                    // console.log('Detected change in app.ts or main.ts, regenerating apiMethods.ts...');
                    generateApiMethods(paths);
                }
            });
        },
        closeBundle() {
            const { execSync } = require('child_process');
            const cfgs = [
                { src: paths.main, out: 'dist-electron/main.cjs', external: 'electron,better-sqlite3' },
                { src: paths.preload, out: 'dist-electron/preload.cjs', external: 'electron' },
                { src: paths.devServer, out: 'dist-electron/backend.cjs', external: 'better-sqlite3' },
            ];
            console.log('Bundling Electron main, preload, and backend using rolldown...');
            for (const cfg of cfgs) {
                execSync(`bunx rolldown ${cfg.src} --file=${cfg.out} --external=${cfg.external} --platform=node --format=cjs --no-code-splitting`, { stdio: 'inherit' });
            }
        },
    };
};

export default electronPlugin;
